-- =============================================================================
-- Help Desk (Projeto Integrador - ADS Uceff) | Script 01: DDL
-- Cria a estrutura das 7 tabelas do MER. SGBD: PostgreSQL 14+
--   psql -h <host> -U helpdesk_user -d helpdesk -f sql/01_ddl.sql
--
-- Observação: este script é equivalente às migrações do Django
-- (python manage.py migrate). Use UM dos dois caminhos. As tabelas auxiliares
-- do framework (sessões, tokens, permissões) são criadas apenas pelo migrate.
-- =============================================================================

BEGIN;

DROP TABLE IF EXISTS historico_status, anexo, comentario, chamado, categoria, usuario, departamento CASCADE;

-- ---------------------------------------------------------------- departamento
CREATE TABLE departamento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL UNIQUE,
    descricao   TEXT         NOT NULL DEFAULT ''
);

-- --------------------------------------------------------------------- usuario
CREATE TABLE usuario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_login       TIMESTAMPTZ  NULL,
    nome             VARCHAR(150) NOT NULL,
    email            VARCHAR(254) NOT NULL UNIQUE,
    senha            VARCHAR(128) NOT NULL,               -- hash PBKDF2 (nunca texto puro)
    perfil           VARCHAR(10)  NOT NULL DEFAULT 'cliente',
    ativo            BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    departamento_id  BIGINT       NULL
        REFERENCES departamento (id) ON DELETE SET NULL,
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('cliente', 'tecnico', 'admin'))
);
CREATE INDEX idx_usuario_departamento ON usuario (departamento_id);

-- ------------------------------------------------------------------- categoria
CREATE TABLE categoria (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(100) NOT NULL,
    descricao        TEXT         NOT NULL DEFAULT '',
    departamento_id  BIGINT       NOT NULL
        REFERENCES departamento (id) ON DELETE RESTRICT,
    CONSTRAINT uq_categoria_dep_nome UNIQUE (departamento_id, nome)
);
CREATE INDEX idx_categoria_departamento ON categoria (departamento_id);

-- --------------------------------------------------------------------- chamado
CREATE TABLE chamado (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo          VARCHAR(150) NOT NULL,
    descricao       TEXT         NOT NULL,
    status          VARCHAR(15)  NOT NULL DEFAULT 'aberto',
    prioridade      VARCHAR(10)  NOT NULL DEFAULT 'media',
    solicitante_id  BIGINT       NOT NULL
        REFERENCES usuario (id) ON DELETE RESTRICT,
    tecnico_id      BIGINT       NULL
        REFERENCES usuario (id) ON DELETE SET NULL,
    categoria_id    BIGINT       NOT NULL
        REFERENCES categoria (id) ON DELETE RESTRICT,
    aberto_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fechado_em      TIMESTAMPTZ  NULL,
    CONSTRAINT ck_chamado_status
        CHECK (status IN ('aberto', 'em_andamento', 'aguardando', 'resolvido', 'fechado')),
    CONSTRAINT ck_chamado_prioridade
        CHECK (prioridade IN ('baixa', 'media', 'alta', 'critica')),
    CONSTRAINT ck_chamado_fechamento
        CHECK (fechado_em IS NULL OR fechado_em >= aberto_em)
);
CREATE INDEX idx_chamado_status       ON chamado (status);
CREATE INDEX idx_chamado_solicitante  ON chamado (solicitante_id);
CREATE INDEX idx_chamado_tecnico      ON chamado (tecnico_id);
CREATE INDEX idx_chamado_categoria    ON chamado (categoria_id);

-- ------------------------------------------------------------------ comentario
CREATE TABLE comentario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id  BIGINT      NOT NULL REFERENCES chamado (id) ON DELETE CASCADE,
    autor_id    BIGINT      NOT NULL REFERENCES usuario (id) ON DELETE RESTRICT,
    texto       TEXT        NOT NULL,
    interno     BOOLEAN     NOT NULL DEFAULT FALSE,           -- nota visível só à equipe
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_comentario_chamado ON comentario (chamado_id);
CREATE INDEX idx_comentario_autor   ON comentario (autor_id);

-- ----------------------------------------------------------------------- anexo
CREATE TABLE anexo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id      BIGINT       NOT NULL REFERENCES chamado (id) ON DELETE CASCADE,
    enviado_por_id  BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE RESTRICT,
    arquivo         VARCHAR(255) NOT NULL,                    -- caminho relativo em MEDIA_ROOT
    enviado_em      TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_anexo_chamado ON anexo (chamado_id);
CREATE INDEX idx_anexo_enviado_por ON anexo (enviado_por_id);

-- ------------------------------------------------------------ historico_status
CREATE TABLE historico_status (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id       BIGINT      NOT NULL REFERENCES chamado (id) ON DELETE CASCADE,
    alterado_por_id  BIGINT      NOT NULL REFERENCES usuario (id) ON DELETE RESTRICT,
    status_anterior  VARCHAR(15) NOT NULL DEFAULT '',
    status_novo      VARCHAR(15) NOT NULL,
    alterado_em      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_historico_chamado ON historico_status (chamado_id);
CREATE INDEX idx_historico_alterado_por ON historico_status (alterado_por_id);

COMMIT;
